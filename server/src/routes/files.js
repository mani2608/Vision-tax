const express = require('express');
const path = require('path');
const fs = require('fs');
const { pool, audit } = require('../db');
const { config } = require('../config');
const { requireAuth } = require('../middleware/auth');
const { asyncRoute } = require('../lib');

const router = express.Router();

// Every download is authorised here. Users get a 404 (not 403) for files that are not theirs
// or not yet released, so file ids cannot be probed.
router.get('/:id/download', requireAuth(), asyncRoute(async (req, res) => {
  const id = Number(req.params.id);
  const notFound = () => res.status(404).json({ error: 'File not found.' });
  if (!Number.isInteger(id) || id < 1) return notFound();

  const [[file]] = await pool.query(
    `SELECT ff.id, ff.kind, ff.stored_name, ff.original_name, ff.mime_type, f.user_id, f.status
       FROM filing_files ff JOIN filings f ON f.id = ff.filing_id WHERE ff.id = ?`,
    [id]
  );
  if (!file) return notFound();

  if (req.user.role !== 'admin') {
    const released = file.kind === 'upload' || file.kind === 'draft' || (file.kind === 'final' && file.status === 'completed');
    if (file.user_id !== req.user.id || !released) return notFound();
  }

  // stored_name is generated by the server (hex + whitelisted extension); re-check defensively
  if (!/^[a-f0-9]{32}\.[a-z]{3,4}$/.test(file.stored_name)) return notFound();
  const full = path.join(config.uploadDir, file.stored_name);
  if (!fs.existsSync(full)) return res.status(410).json({ error: 'The file is no longer available on the server.' });

  if (req.user.role === 'user') {
    await pool.query('INSERT INTO file_downloads (user_id, file_id) VALUES (?, ?)', [req.user.id, file.id]);
  } else {
    await audit(req.user.id, 'file.download', 'file', file.id, null, req.ip);
  }
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('Cache-Control', 'private, no-store');
  res.download(full, file.original_name, (err) => {
    if (err && !res.headersSent) res.status(500).json({ error: 'Download failed.' });
  });
}));

module.exports = router;
